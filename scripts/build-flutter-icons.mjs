// Generates packages/nuzul_ui/lib/src/generated/icon_names.dart and icon_extra.dart from scripts/icons/set.mjs,
// so the web (Flux overrides) and Flutter share one icon set. Run from the repo root.
import { writeFileSync, readFileSync } from 'node:fs';
import { icons } from './icons/set.mjs';

const baseNames = new Set(
  [...readFileSync('packages/nuzul_ui/lib/src/generated/icon_data.dart', 'utf8').matchAll(/^ {2}'([a-z-]+)': \[/gm)].map((m) => m[1]),
);

/** Parses M L H V Z (absolute and relative) into polylines of [x, y, x, y ...]. Arcs are not supported. */
function parse(d) {
  const tokens = [...d.matchAll(/([MmLlHhVvZzAa])|(-?\d*\.?\d+(?:e-?\d+)?)/g)].map((m) => m[1] ?? parseFloat(m[2]));
  const out = [];
  let cur = null;
  let x = 0, y = 0, sx = 0, sy = 0, cmd = null;
  let i = 0;
  const num = () => tokens[i++];
  const push = (px, py) => { cur.points.push(+px.toFixed(3), +py.toFixed(3)); x = px; y = py; };
  while (i < tokens.length) {
    if (typeof tokens[i] === 'string') cmd = tokens[i++];
    if (cmd === 'A' || cmd === 'a') return null;
    switch (cmd) {
      case 'M': case 'm': {
        const nx = cmd === 'm' ? x + num() : num();
        const ny = cmd === 'm' ? y + num() : num();
        cur = { points: [], closed: false };
        out.push(cur);
        push(nx, ny);
        sx = nx; sy = ny;
        cmd = cmd === 'm' ? 'l' : 'L';
        break;
      }
      case 'L': push(num(), num()); break;
      case 'l': push(x + num(), y + num()); break;
      case 'H': push(num(), y); break;
      case 'h': push(x + num(), y); break;
      case 'V': push(x, num()); break;
      case 'v': push(x, y + num()); break;
      case 'Z': case 'z':
        cur.closed = true; x = sx; y = sy; cmd = null;
        break;
      default: throw new Error(`bad path ${d}`);
    }
  }
  return out;
}

const camel = (n) => n.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const names = Object.keys(icons);
const extraBody = [];
const supported = [];
for (const name of names) {
  const { paths = [], solid = [] } = icons[name];
  const strokes = [];
  let ok = true;
  for (const [list, filled] of [[paths, false], [solid, true]]) {
    for (const d of list) {
      const polys = parse(d);
      if (!polys) { ok = false; break; }
      for (const p of polys) strokes.push(`_NzStroke([${p.points.join(', ')}], closed: ${p.closed || filled}, filled: ${filled})`);
    }
  }
  if (!ok) continue; // the moon uses arcs; Flutter has no use for it
  supported.push(name);
  if (!baseNames.has(name)) extraBody.push(`  '${name}': [${strokes.join(', ')}],`);
}

writeFileSync('packages/nuzul_ui/lib/src/generated/icon_extra.dart', `// GENERATED by scripts/build-flutter-icons.mjs from scripts/icons/set.mjs — do not edit by hand.

part of '../icons.dart';

/// Icons beyond the 20 of the v3 identity, drawn by the same rules (24 grid, 2px stroke, miter joins, square caps).
const Map<String, List<_NzStroke>> _nzIconExtra = {
${extraBody.join('\n')}
};
`);

writeFileSync('packages/nuzul_ui/lib/src/generated/icon_names.dart', `// GENERATED by scripts/build-flutter-icons.mjs from scripts/icons/set.mjs — do not edit by hand.

part of '../icons.dart';

/// Names of the icon set (24 grid, 2px stroke, miter joins, square caps, only 0/35/45/90 degree lines).
abstract final class NzIcons {
${supported.map((n) => `  static const ${camel(n)} = '${n}';`).join('\n')}

  static Iterable<String> get all => _nzIconAll.keys;
}
`);
