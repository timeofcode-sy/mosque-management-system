// Generates backend/resources/views/flux/icon/*.blade.php (Flux resolves app views first) from scripts/icons/set.mjs.
// Run from the repo root: node scripts/build-web-icons.mjs
import { mkdirSync, writeFileSync, readdirSync, unlinkSync } from 'node:fs';
import { icons, flux } from './icons/set.mjs';

const dir = 'backend/resources/views/flux/icon';
mkdirSync(dir, { recursive: true });
for (const f of readdirSync(dir)) if (f.endsWith('.blade.php')) unlinkSync(`${dir}/${f}`);

const body = ({ paths = [], solid = [] }) =>
  [...paths.map((d) => `    <path d="${d}" />`), ...solid.map((d) => `    <path d="${d}" fill="currentColor" stroke="none" />`)].join('\n');

for (const [name, target] of Object.entries(flux)) {
  const icon = icons[target];
  if (!icon) throw new Error(`no icon ${target} for ${name}`);
  writeFileSync(`${dir}/${name}.blade.php`, `{{-- GENERATED by scripts/build-web-icons.mjs (icon "${target}" of the Nuzulan set) — do not edit by hand. --}}
@props([
    'variant' => 'outline',
])

@php
    $classes = Flux::classes('shrink-0')->add(
        match ($variant) {
            'mini' => '[:where(&)]:size-5',
            'micro' => '[:where(&)]:size-4',
            default => '[:where(&)]:size-6',
        },
    );
@endphp

<svg
    {{ $attributes->class($classes) }}
    data-flux-icon
    xmlns="http://www.w3.org/2000/svg"
    viewBox="0 0 24 24"
    fill="none"
    stroke="currentColor"
    stroke-width="2"
    stroke-linecap="square"
    stroke-linejoin="miter"
    aria-hidden="true"
    data-slot="icon"
>
${body(icon)}
</svg>
`);
}
console.log(Object.keys(flux).length, 'flux icons written');
