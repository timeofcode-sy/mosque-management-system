// Generates backend/resources/css/nuzul-tokens.css and nuzul-kit.css from the v3 identity folder.
// Run: node scripts/build-web-tokens.mjs   (from the repo root)
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync('brand-v3/identity/design-system/tokens.json', 'utf8'));
const web = readFileSync('brand-v3/identity/web/nuzul.css', 'utf8');

const light = [];
const dark = [];
const fixed = [];
for (const t of tokens.color.tokens) {
  if (typeof t.value === 'string') fixed.push(`  --${t.name}: ${t.value};`);
  else { light.push(`  --${t.name}: ${t.value.light};`); dark.push(`  --${t.name}: ${t.value.dark};`); }
}
for (const t of tokens.shadow.tokens) {
  light.push(`  --${t.name}: ${t.value.light};`);
  dark.push(`  --${t.name}: ${t.value.dark};`);
}

// Non-colour tokens: spacing, radius, size, breakpoint, geometry and the three font families.
const other = [];
for (const group of ['spacing', 'radius', 'size', 'breakpoint', 'geometry']) {
  for (const t of tokens[group].tokens) other.push(`  --${t.name}: ${t.value};`);
}
for (const [name, value] of Object.entries(tokens.type.families)) other.push(`  --font-${name}: ${value};`);

const out = `/* GENERATED by scripts/build-web-tokens.mjs from brand-v3/identity/design-system/tokens.json — do not edit by hand. */
:root {
${fixed.join('\n')}
${other.join('\n')}
${light.join('\n')}
  color-scheme: light;
}

.dark {
${dark.join('\n')}
  color-scheme: dark;
}
`;
writeFileSync('backend/resources/css/nuzul-tokens.css', out);

// The component part of the v3 web kit (everything after the "Nuzulan components" banner).
const start = web.indexOf('/* Nuzulan components.');
let kit = web.slice(start)
  .replace(/url\("pattern\//g, 'url("/brand/pattern/');
kit = `/* GENERATED by scripts/build-web-tokens.mjs from brand-v3/identity/web/nuzul.css — do not edit by hand. */\n` + kit;
writeFileSync('backend/resources/css/nuzul-kit.css', kit);
console.log('ok', light.length, dark.length, fixed.length);
