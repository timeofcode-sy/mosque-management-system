<?php

namespace App\Contracts;

/**
 * صفٌّ تُزامنه تطبيقات فلاتر — أي صفّ يحمل uuid وتحتاجه شاشةُ عميل.
 *
 * تنفيذُ هذه الواجهة هو **الإعلانُ الوحيد** بأن الجدول يدخل change_log: مراقبُ
 * App\Concerns\RecordsSyncChanges لا يسجّل صفّاً لا يحسم معهده. ولذلك بقيت users
 * خارجها عمداً — حمولتها بيانات دخول لا تُبثّ في تيّار تغييرات يقرؤه كل جهاز في المعهد.
 */
interface Syncable
{
    /**
     * معهد الصفّ — مباشرةً من عموده، أو عبر أبيه بـ App\Support\SyncScope::via().
     *
     * null يعني «لا معهد له» فلا يُسجَّل تغييرُه: صفٌّ يتيم أو أبٌ حُذف حذفاً قاسياً.
     */
    public function syncInstituteId(): ?int;
}
